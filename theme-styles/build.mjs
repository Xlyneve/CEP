// Rebuild selected-theme bundles after editing source.css. Run: node theme-styles/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {readStyleRules, splitStyleText} from '../search-style-parser.js';
const folder=path.dirname(fileURLToPath(import.meta.url));
const source=fs.readFileSync(path.join(folder,'source.css'),'utf8');
const themes=['oyster-mist','blush-marble','clay-relief','original','moon-clay','cloud-glass','midnight-glass','warm-ivory','opal-pearl','pastel-rose-5d','pastel-rose-recessed','lavender-glass','grey-lavender','pearl-silver','frost-outline','porcelain','aurora','soft-stone','mint-ceramic','autumn','hoya','lake-mist','palm-springs','quiet-stone','sculpted','pastel-jumper'];
  function selectedThemeCss(text, theme) {
    text = text.replace(/\/\*[\s\S]*?\*\//g, '');
    function select(source) {
      let output = '', cursor = 0;
      while (cursor < source.length) {
        let open = -1, quote = '', depth = 0;
        for (let i = cursor; i < source.length; i++) {
          const c = source[i];
          if (quote) { if (c === quote && source[i - 1] !== '\\') quote = ''; continue; }
          if (c === '"' || c === "'") { quote = c; continue; }
          if (c === '(' || c === '[') depth++;
          else if (c === ')' || c === ']') depth--;
          if (c === '{' && depth === 0) { open = i; break; }
        }
        if (open < 0) break;
        let close = open + 1, braces = 1; quote = '';
        for (; close < source.length; close++) {
          const c = source[close];
          if (quote) { if (c === quote && source[close - 1] !== '\\') quote = ''; continue; }
          if (c === '"' || c === "'") { quote = c; continue; }
          if (c === '{') braces++;
          else if (c === '}' && --braces === 0) break;
        }
        const header = source.slice(cursor, open).trim();
        const body = source.slice(open + 1, close);
        cursor = close + 1;
        if (/^@(media|supports|layer|container)\b/.test(header)) {
          const inner = select(body);
          if (inner) output += `${header}{${inner}}\n`;
        } else if (header.startsWith('@')) {
          output += `${header}{${body}}\n`;
        } else {
          // A comma outside parentheses/brackets separates independent selectors.
          const selectors = []; let start = 0; depth = 0; quote = '';
          for (let i = 0; i < header.length; i++) {
            const c = header[i];
            if (quote) { if (c === quote && header[i - 1] !== '\\') quote = ''; continue; }
            if (c === '"' || c === "'") { quote = c; continue; }
            if (c === '(' || c === '[') depth++;
            else if (c === ')' || c === ']') depth--;
            if (c === ',' && depth === 0) { selectors.push(header.slice(start, i)); start = i + 1; }
          }
          selectors.push(header.slice(start));
          const applies = selectors.some(selector => {
            if (/:not\([^)]*\[data-xlyneve-color-theme/.test(selector)) return true;
            const themes = [...selector.matchAll(/\[data-xlyneve-color-theme\s*=\s*["']([^"']+)["']\]/g)];
            return !themes.length || themes.some(match => match[1] === theme);
          });
          if (applies) output += `${header}{${body}}\n`;
        }
      }
      return output;
    }
    return select(text);
  }
function bootRules(rules){
  let css='';
  for(const rule of rules){
    if(rule.rules){const inner=bootRules(rule.rules);if(inner)css+=`${rule.header}{${inner}}\n`;continue;}
    if(!rule.body || !rule.header.includes('[data-xlyneve-color-theme='))continue;
    const pageOnly=splitStyleText(rule.header,',').every(selector=>{
      if(/\bbody\s*:(?:is|where|has|not)\(/.test(selector))return false;
      const plain=selector.trim().replace(/\[[^\]]*\]|:[\w-]+\([^)]*\)/g,'');
      return /^html[^\s]*$/.test(plain) || /^html[^\s]*\s+body(?:::before|::after)?$/.test(plain);
    });
    if(pageOnly)css+=`${rule.header}{${rule.body}}\n`;
  }
  return css;
}
// Compile source-card aliases at build time using the shared search compiler.
const searchSource=fs.readFileSync(path.join(folder,'../search-source-cards.js'),'utf8').replace(/\r\n/g,'\n');
const compileStart=searchSource.indexOf('  function compile(rules) {');
const compileSource=searchSource.slice(compileStart,searchSource.indexOf('\n  }\n',compileStart)+5);
const classes=Function('return '+searchSource.match(/const classes = (.*);/)[1])();
const contexts=Function('return '+searchSource.match(/const pageContexts = (.*);/)[1])();
const compileSearch=Function('classes','pageContexts','splitStyleText',compileSource+';return compile;')(classes,contexts,splitStyleText);
const boot={};
for(const theme of themes){
  const css=selectedThemeCss(source,theme);
  fs.writeFileSync(path.join(folder,theme+'.css'),`/* CEP theme bundle: ${theme}. Generated by build.mjs; edit source.css. */\n`+css+'\n/* Search cards use the same selected-theme material. */\n'+compileSearch(readStyleRules(css)));
  boot[theme]=bootRules(readStyleRules(css));
}
const version=createHash('sha256').update(source).update(compileSource).update(JSON.stringify(classes)).update(JSON.stringify(contexts)).digest('hex').slice(0,12);
const generated=`// BEGIN GENERATED THEME_BOOT\n  const themeCssVersion = ${JSON.stringify(version)};\n  const themeBootCss = ${JSON.stringify(boot)};\n  // END GENERATED THEME_BOOT`;
const main=path.join(folder,'../page-theme.js');
let js=fs.readFileSync(main,'utf8');
if(js.includes('// BEGIN GENERATED THEME_BOOT'))js=js.replace(/\/\/ BEGIN GENERATED THEME_BOOT[\s\S]*?\/\/ END GENERATED THEME_BOOT/,()=>generated);
else js=js.replace('  const themeStyle = document.createElement("style");','  '+generated+'\n\n  const themeStyle = document.createElement("style");');
fs.writeFileSync(main,js);
console.log(`Built ${themes.length} theme bundles (${version}); each preserves shared/theme rule order.`);
